with open('src/data/items.h', 'r', encoding='utf-8') as f:
    content = f.read()

# Build C code block
lines = []
for const_id, name, desc, pocket in items_data:
    lines.append(f"""    [{const_id}] =
    {{
        .name = ITEM_NAME("{name}"),
        .price = 500,
        .description = COMPOUND_STRING(
            "{desc}"),
        .pocket = {pocket},
        .sortType = ITEM_TYPE_BAG_MENU,
        .type = ITEM_USE_BAG_MENU,
        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,
        .iconPic = gItemIcon_QuestionMark,
        .iconPalette = gItemIconPalette_QuestionMark,
    }},""")

block = "\n".join(lines)

# Insert right before "};\n\n#undef ITEM_NAME"
target = "};\n\n#undef ITEM_NAME"
new_content = content.replace(target, block + "\n" + target)

with open('src/data/items.h', 'w', encoding='utf-8') as f:
    f.write(new_content)

